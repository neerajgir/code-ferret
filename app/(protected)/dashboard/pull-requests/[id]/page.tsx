import type { Metadata } from "next";
import { notFound } from "next/navigation";
// The default phosphor entry uses React context and breaks in RSC —
// server components must use the SSR build.
import { ArrowSquareOutIcon } from "@phosphor-icons/react/ssr";
import { formatDistanceToNow } from "date-fns";

import { Button } from "@/components/ui/button";
import {
  Card,
  CardAction,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { DashboardHeader } from "@/features/dashboard/components/dashboard-header";
import { statusBadge } from "@/features/dashboard/lib/status-style";
import { requiredAuth } from "@/features/auth/actions";
import { AiReviewMarkdown } from "@/features/pull-requests/components/ai-review-markdown";
import {
  PULL_REQUEST_STATUS_LABEL,
  pullRequestStatusTone,
  type PullRequestStatus,
} from "@/features/pull-requests/lib/status";
import { getPullRequestById } from "@/features/pull-requests/server/get-pull-requests";

export const metadata: Metadata = {
  title: "Pull Request · Dashboard",
};

type PullRequestDetailPageProps = {
  /** Dynamic segment is a promise in the App Router — await before use. */
  params: Promise<{ id: string }>;
};

/**
 * Single pull request page: metadata card plus the AI review rendered
 * as markdown (or a status-specific explanation while the review is
 * still running).
 */
export default async function PullRequestDetailPage({
  params,
}: PullRequestDetailPageProps) {
  const { id } = await params;
  const session = await requiredAuth();
  const pullRequest = await getPullRequestById(session.user.id, id);

  if (!pullRequest) {
    notFound();
  }

  const githubUrl = `https://github.com/${pullRequest.repoFullName}/pull/${pullRequest.prNumber}`;

  return (
    <>
      <DashboardHeader
        title={`${pullRequest.repoFullName} · #${pullRequest.prNumber}`}
        description={pullRequest.title}
      />
      <div className="flex flex-1 flex-col gap-6 p-6">
        <Card>
          <CardHeader>
            <CardTitle>{pullRequest.title}</CardTitle>
            <CardDescription>
              Opened by {pullRequest.authorLogin ?? "unknown"} · base{" "}
              {pullRequest.baseBranch}
            </CardDescription>
            <CardAction>
              <span
                className={statusBadge(pullRequestStatusTone(pullRequest.status))}
              >
                {PULL_REQUEST_STATUS_LABEL[pullRequest.status]}
              </span>
            </CardAction>
          </CardHeader>
          <CardContent>
            <dl className="grid grid-cols-2 gap-4 sm:grid-cols-4">
              <MetaItem label="Repository" value={pullRequest.repoFullName} />
              <MetaItem label="Pull request" value={`#${pullRequest.prNumber}`} />
              <MetaItem label="Base branch" value={pullRequest.baseBranch} />
              <MetaItem
                label="Head commit"
                value={pullRequest.headSha.slice(0, 7)}
              />
              <MetaItem
                label="Created"
                value={relativeTime(pullRequest.createdAt)}
              />
              <MetaItem
                label="Reviewed"
                value={
                  pullRequest.reviewedAt
                    ? relativeTime(pullRequest.reviewedAt)
                    : "Not yet"
                }
              />
            </dl>
            <div className="mt-4">
              <Button
                variant="outline"
                nativeButton={false}
                render={
                  <a href={githubUrl} target="_blank" rel="noreferrer" />
                }
              >
                View on GitHub
                <ArrowSquareOutIcon />
              </Button>
            </div>
          </CardContent>
        </Card>

        <Card>
          <CardHeader>
            <CardTitle>AI review</CardTitle>
            <CardDescription>
              Generated by Code Ferret from the pull request diff and your
              synced codebase context.
            </CardDescription>
          </CardHeader>
          <CardContent>
            <ReviewContent
              status={pullRequest.status}
              reviewComment={pullRequest.reviewComment}
            />
          </CardContent>
        </Card>
      </div>
    </>
  );
}

function MetaItem({ label, value }: { label: string; value: string }) {
  return (
    <div className="flex min-w-0 flex-col gap-0.5">
      <dt className="text-xs text-muted-foreground">{label}</dt>
      <dd className="truncate text-sm font-medium">{value}</dd>
    </div>
  );
}

function relativeTime(value: string | null): string {
  if (!value) {
    return "—";
  }

  return formatDistanceToNow(new Date(value), { addSuffix: true });
}

type ReviewContentProps = {
  status: PullRequestStatus;
  reviewComment: string | null;
};

function ReviewContent({ status, reviewComment }: ReviewContentProps) {
  if (status === "reviewed") {
    if (!reviewComment) {
      return (
        <p className="text-sm text-muted-foreground">
          The review finished without code comments — there was nothing to
          flag in this pull request.
        </p>
      );
    }

    return <AiReviewMarkdown markdown={reviewComment} />;
  }

  if (status === "processing") {
    return (
      <p className="text-sm text-muted-foreground">
        The AI review is running right now. Refresh this page in a moment to
        see the result.
      </p>
    );
  }

  if (status === "rate_limited") {
    return (
      <p className="text-sm text-muted-foreground">
        The review hit the GitHub API rate limit. It will run automatically on
        the next pull request event, or you can re-trigger it by pushing a new
        commit.
      </p>
    );
  }

  return (
    <p className="text-sm text-muted-foreground">
      The review is queued and will start shortly. Refresh this page in a
      moment to see the result.
    </p>
  );
}
